import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
DOCS_DIR = ROOT / "docs"
DOCS_DIR.mkdir(exist_ok=True)


def load_json(p):
    with open(p, "r", encoding="utf-8") as f:
        return json.load(f)


def fmt_price(p):
    if p is None:
        return "-"
    return f"¥{p:,}"


